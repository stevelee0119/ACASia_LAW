    return NormalizedDocument(
        document_id="d1",
        filename="synthetic_timeline_p1_p3.pdf",
        mime_type="application/pdf",
        sha256="0" * 64,
        pages=[Page(page_number=1, blocks=[block], width=595.0, height=842.0)],
    )


