("INCAPACITATED","본인은 정신을 차리지 못한 상태에서 상대방이 차를 몰고 떠나는 것을 보았습니다."),
("ELSEWHERE_SAME_TIME","저는 그 시각 집에 머물면서 아무 연락도 받지 않았는데도, 같은 시각 사무실에서 팀장이 한 말을 제 귀로 들었습니다."),
("ELSEWHERE_SAME_TIME","증인은 서울 본사에 있으면서 외부와 통화하지 않았지만 같은 시각 부산 지점에서 오간 대화를 직접 들었습니다."),
